// Packs the Phosphor duotone icons the website uses (MIT, https://phosphoricons.com) into website/src/lib/icons.ts
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets', 'duotone');
const NAMES = ['scribble-loop', 'selection', 'monitor', 'translate', 'file-pdf', 'notebook', 'brain', 'cloud-slash', 'key', 'download-simple',
  'github-logo', 'windows-logo', 'play', 'pause', 'speaker-high', 'check-circle', 'copy', 'magic-wand', 'sparkle', 'lightning', 'globe', 'lock-simple',
  'text-aa', 'cpu', 'books', 'keyboard', 'hand-waving', 'rocket-launch', 'shield-check', 'wifi-slash', 'clipboard-text', 'terminal-window', 'cloud-arrow-down',
  'plus', 'minus', 'arrow-square-out', 'image-square', 'bug', 'calculator', 'list-bullets', 'heart', 'star', 'x'];
const out = {};
for (const n of NAMES) {
  const f = path.join(dir, `${n}-duotone.svg`);
  if (!fs.existsSync(f)) { console.error('missing icon', n); process.exit(1); }
  out[n] = fs.readFileSync(f, 'utf8').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
}
const ts = `/* generated by tools/build_site_icons.js - Phosphor duotone icons (MIT, https://phosphoricons.com) */
const PATHS: Record<string, string> = ${JSON.stringify(out)};

export type IconName = keyof typeof PATHS;

export function svg(name: string): string {
  return '<svg viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false">' + (PATHS[name] ?? '') + '</svg>';
}

/** Fill every <i data-i="name"> under root with its icon. */
export function hydrateIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('i[data-i]:not([data-done])').forEach((el) => {
    el.innerHTML = svg(el.dataset.i ?? '');
    el.dataset.done = '1';
  });
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'website', 'src', 'lib', 'icons.ts'), ts);
console.log('website/src/lib/icons.ts', Object.keys(out).length, 'icons', (ts.length / 1024).toFixed(0) + 'KB');
