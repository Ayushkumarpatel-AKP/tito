// "Save as PDF": a clean A4 page with the title, the picture you selected, the answer and a footer.
// Rendered from HTML with Electron's own printToPDF, so no extra dependency and it works offline.
const { BrowserWindow, dialog, app } = require('electron');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { pathToFileURL } = require('url');

const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const fileUrl = (p) => pathToFileURL(path.join(__dirname, '..', p)).href;

/** Same light formatting the card understands: "- " bullets, "1." steps, **bold**, `code`. */
function inline(t) {
  return esc(t).replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>').replace(/`([^`]+)`/g, '<code>$1</code>');
}
function body(answer) {
  const lines = String(answer || '').split(/\n+/).map((l) => l.trim()).filter(Boolean);
  let html = '', open = null;
  const close = () => { if (open) { html += `</${open}>`; open = null; } };
  for (const ln of lines) {
    const m = ln.match(/^(?:[-*•]\s+|(\d+)[.)]\s+)(.*)$/);
    if (m) { const t = m[1] ? 'ol' : 'ul'; if (open !== t) { close(); html += `<${t}>`; open = t; } html += `<li>${inline(m[2])}</li>`; }
    else { close(); html += `<p>${inline(ln)}</p>`; }
  }
  close(); return html;
}

function entryHtml(e) {
  const when = new Date(e.ts || Date.now()).toLocaleString();
  const meta = [when, e.provider || (e.via === 'ocr' ? 'Offline text reader' : e.via === 'llm' ? 'Offline AI' : '')].filter(Boolean).join('  -  ');
  return `<article>
    <h2>${esc(e.title || 'Tito')}</h2>
    <div class="meta">${esc(meta)}</div>
    ${e.image || e.thumb ? `<img class="shot" src="${e.image || e.thumb}">` : ''}
    <div class="answer">${body(e.answer)}</div>
  </article>`;
}

function pageHtml(entries, heading) {
  return `<!doctype html><html><head><meta charset="utf-8"><style>
    @font-face { font-family: Nunito; font-weight: 400; src: url('${fileUrl('assets/fonts/nunito-latin-400-normal.woff2')}'); }
    @font-face { font-family: Nunito; font-weight: 700; src: url('${fileUrl('assets/fonts/nunito-latin-700-normal.woff2')}'); }
    @font-face { font-family: Nunito; font-weight: 800; src: url('${fileUrl('assets/fonts/nunito-latin-800-normal.woff2')}'); }
    * { box-sizing: border-box; }
    body { font-family: Nunito, 'Segoe UI', 'Nirmala UI', sans-serif; color: #33244d; margin: 0; font-size: 12.5pt; line-height: 1.6; }
    header { display: flex; align-items: center; gap: 12px; padding-bottom: 12px; margin-bottom: 18px; border-bottom: 3px solid #ffc7dc; }
    header img { width: 42px; height: 42px; } header b { font-size: 18pt; font-weight: 800; } header span { color: #85729e; font-size: 10pt; margin-left: auto; }
    article { page-break-inside: avoid; margin-bottom: 26px; }
    h2 { font-size: 19pt; font-weight: 800; line-height: 1.2; margin: 0 0 4px; color: #2b1c44; }
    .meta { font-size: 9.5pt; color: #85729e; margin-bottom: 12px; }
    .shot { display: block; max-width: 100%; max-height: 260px; object-fit: contain; border-radius: 12px; border: 1px solid #ecd5e6; margin: 0 0 14px; background: #fff; }
    .answer p { margin: 0 0 9px; } .answer ul, .answer ol { margin: 0 0 9px; padding-left: 22px; } .answer li { margin: 3px 0; }
    .answer strong { font-weight: 800; } .answer code { font-family: Consolas, monospace; background: #f6e8f3; color: #8a2f66; padding: 1px 5px; border-radius: 5px; font-size: 11pt; }
    footer { margin-top: 20px; padding-top: 8px; border-top: 1px solid #ecd5e6; color: #85729e; font-size: 9pt; }
  </style></head><body>
    <header><img src="${fileUrl('assets/icon.png')}"><b>${esc(heading)}</b><span>Made with Tito</span></header>
    ${entries.map(entryHtml).join('')}
    <footer>Generated by Tito, your screen buddy.</footer>
  </body></html>`;
}

async function render(html) {
  const tmp = path.join(os.tmpdir(), `tito-pdf-${process.pid}-${Date.now()}.html`);
  fs.writeFileSync(tmp, html);
  const win = new BrowserWindow({ show: false, webPreferences: { sandbox: true } });
  try {
    await win.loadFile(tmp);
    await win.webContents.executeJavaScript('document.fonts.ready.then(() => true)');
    return await win.webContents.printToPDF({ pageSize: 'A4', printBackground: true, margins: { top: 0.5, bottom: 0.6, left: 0.65, right: 0.65 } });
  } finally { win.destroy(); fs.rm(tmp, { force: true }, () => {}); }
}

/** Ask where to save, then write the PDF. Returns { ok, path } (ok false when cancelled). */
async function save(entries, heading, defaultName, parent) {
  if (process.env.TITO_SELFTEST_PDF) { fs.writeFileSync(process.env.TITO_SELFTEST_PDF, await render(pageHtml(entries, heading))); return { ok: true, path: process.env.TITO_SELFTEST_PDF }; }
  const r = await dialog.showSaveDialog(parent || undefined, {
    defaultPath: path.join(app.getPath('documents'), defaultName), filters: [{ name: 'PDF', extensions: ['pdf'] }],
  });
  if (r.canceled || !r.filePath) return { ok: false };
  fs.writeFileSync(r.filePath, await render(pageHtml(entries, heading)));
  return { ok: true, path: r.filePath };
}

/** For tests: render without a dialog. */
const renderToBuffer = (entries, heading) => render(pageHtml(entries, heading));

const safeName = (s) => String(s || 'tito').replace(/[^\w\- ]+/g, '').trim().slice(0, 40).replace(/\s+/g, '-') || 'tito';
module.exports = { save, renderToBuffer, safeName };
